import { formatDateTime } from "@/lib/dates";

export function PrintDocumentHeader({ title, subtitle, details = [], generatedAt = new Date(), generatedPrefix = "Generated" }: {
  title: string;
  subtitle?: string;
  /** Scope lines such as filters or prepared-by; blank entries are skipped. */
  details?: (string | false | null | undefined)[];
  generatedAt?: Date;
  generatedPrefix?: string;
}) {
  const detailLines = details.filter((line): line is string => Boolean(line));

  return <header className="print-document-header">
    <img src="/mendez-christian-academy-seal.png" alt="Mendez Christian Academy seal" />
    <div className="print-document-heading">
      <p className="print-school-name">MENDEZ CHRISTIAN ACADEMY</p>
      <h1>{title}</h1>
      {subtitle && <p className="print-document-subtitle">{subtitle}</p>}
      {detailLines.length > 0 && <p className="print-document-details">{detailLines.join(" · ")}</p>}
    </div>
    <p className="print-generated">{generatedPrefix}<br />{formatDateTime(generatedAt)}</p>
  </header>;
}

export function PrintDocumentFooter({ preparedBy }: { preparedBy?: string }) {
  return <footer className="print-document-footer">
    <span>System-generated by EducaTrak{preparedBy ? ` for ${preparedBy}` : ""}. Figures reflect recorded transactions at generation time.</span>
    <span>This document does not indicate approval or certification.</span>
  </footer>;
}
